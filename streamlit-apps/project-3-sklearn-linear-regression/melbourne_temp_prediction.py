# کتابخونه‌های لازم برای کار با آرایه، خوندن فایل CSV، رسم نمودار، و ساختن مدل رگرسیون خطی
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from sklearn.linear_model import LinearRegression
import streamlit as st
#============================================================================



#============================================================================
st.title(" پروژه ۳: پیش‌بینی دمای ملبورن با سایکیت لرن")
st.write("""همون مفهوم پروژه‌ی ۲، این‌بار با استفاده از سایکیت لرن به‌جای
پیاده‌سازی دستی، روی یه دیتاست واقعی و بزرگ.

 این پروژه چیکار می‌کنه؟

- دیتاست دمای کمینه‌ی روزانه‌ی ملبورن (۱۹۸۱ تا ۱۹۹۰) رو با پانداس می‌خونه
- یه مدل رگرسیون خطی با سایکیت لرن می‌سازه و آموزش می‌ده
- دمای روز بعد از آخرین داده رو پیش‌بینی می‌کنه
- نموداری از داده‌های واقعی و خط پیش‌بینی مدل رسم می‌کنه""")
st.caption("این مدل برای نمایش فرآیند ساخت یک اپلیکیشن پیش‌بینی طراحی شده و دقت آن به داده‌های ورودی بستگی دارد.")

# خوندن دیتاست دمای کمینه‌ی روزانه‌ی ملبورن (از سال 1981 تا 1990)
data = pd.read_csv("daily-min-temperatures.csv")
temp = data["Temp"].values
x = []
y = temp
for i in range(len(temp)):
    x.append(i + 1)
x = np.array(x).reshape(-1, 1)

if st.checkbox("نمایش دیتاست"):
    st.dataframe(data)
#============================================================================



#============================================================================
# ساختن مدل Linear Regression و آموزش دادنش با داده‌های واقعی 
model = LinearRegression()
model.fit(x, y)
#============================================================================



#============================================================================
# نمایش پیشبینی دما برای یک روز جلو تراز اخرین داده ای که داریم
day_to_predict = np.array([[len(temp) + 1]])
prediction = model.predict(day_to_predict).round(2)
if st.button("پیشبینی دمای روز بعد"):
    st.success(f"پیشبینی روز بعد: {prediction}")

# نمودار: نقطه‌های دمای واقعی (آبی) + خط پیش‌بینی مدل (قرمز)
    fig, ax = plt.subplots()
    ax.scatter(x, y, label="Actual Temperature", s=5, alpha=0.5)
    ax.plot(x, model.predict(x), color="red", label="Regression Line", linewidth=2)
    ax.set_xlabel("Day Number")
    ax.set_ylabel("Temperature (°C)")
    ax.set_title("Melbourne Daily Minimum Temperature Prediction")
    ax.legend()
    st.pyplot(fig)
#============================================================================